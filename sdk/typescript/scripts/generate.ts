/**
 * Regenerates src/schema.ts from an OpenAPI spec.
 *
 *   bun run generate                                  # from ../../docs/openapi.json
 *   bun run generate https://api.barrelman.dev/docs/json
 *   bun run generate path/to/openapi.json
 *   bun run check:schema                              # fail if src/schema.ts is stale
 *
 * The default is the spec committed beside the docs, so the types track the
 * same document the public API reference is built from. CI runs --check to
 * catch a spec refresh that forgot to regenerate the types.
 */
import openapiTS, { astToString } from 'openapi-typescript'
import { resolve } from 'node:path'

const here = import.meta.dir
const out = resolve(here, '../src/schema.ts')
const args = process.argv.slice(2)
const check = args.includes('--check')
const spec = args.find((arg) => !arg.startsWith('--')) ?? resolve(here, '../../../docs/openapi.json')

const HEADER = `/**
 * Generated by openapi-typescript from the Barrelman OpenAPI spec.
 * Do not edit by hand: run \`bun run generate\` in sdk/typescript.
 */

`

/**
 * The console SPA and the admin API are in the spec for the docs site, but a
 * client for the public API has no use for them, and the console's two routes
 * share an operationId that openapi-typescript refuses.
 */
const EXCLUDED = /^\/(console|admin)(\/|$)/

async function render(source: string): Promise<string> {
  const doc = /^https?:\/\//.test(source)
    ? await (await fetch(source)).json()
    : await Bun.file(resolve(process.cwd(), source)).json()
  doc.paths = Object.fromEntries(Object.entries(doc.paths ?? {}).filter(([path]) => !EXCLUDED.test(path)))
  const ast = await openapiTS(doc)
  return HEADER + astToString(ast)
}

const generated = await render(spec)

if (check) {
  const current = await Bun.file(out).text().catch(() => '')
  if (current !== generated) {
    console.error(`src/schema.ts is out of date with ${spec}. Run \`bun run generate\` in sdk/typescript.`)
    process.exit(1)
  }
  console.log('src/schema.ts is up to date.')
} else {
  await Bun.write(out, generated)
  console.log(`Wrote ${out} from ${spec}`)
}
